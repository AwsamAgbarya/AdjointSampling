class NoiseSchedule:
    """
    Base process with diffusion coefficient sigma(t) and nu_t = int_0^t sigma(s)^2 ds.
        marginal   p_t(x)            = N(0, nu_t I)                                  (43)
        posterior  p_{t|1}(x | X_1)  = N(alpha_t X_1, alpha_t (nu_1 - nu_t) I),
                   alpha_t = nu_t / nu_1                                              (44-45)
    On the zero-CoM subspace these are the same Gaussians restricted to it (Sec. 3.4.1)."""
 
    def sigma(self, t):
        raise NotImplementedError
 
    def nu(self, t):
        raise NotImplementedError
 
    @property
    def nu1(self):
        return float(self.nu(torch.tensor(1.0, dtype=torch.float64)))
 
    def sample_marginal(self, t, shape, generator=None, device=None):
        t = torch.as_tensor(t, dtype=torch.float32, device=device).reshape(-1, 1, 1)
        z = center(torch.randn(shape, generator=generator, device=device))
        return self.nu(t).sqrt() * z
 
    def posterior_params(self, t):
        nu_t = self.nu(t)
        alpha = nu_t / self.nu1
        return alpha, alpha * (self.nu1 - nu_t)
 
    def sample_posterior(self, t, x1):
        """X_t ~ p^base_{t|1}(. | X_1), t: (B,), x1: (B, n, d)."""
        alpha, var = self.posterior_params(t.reshape(-1, 1, 1))
        return alpha * x1 + var.clamp_min(0).sqrt() * center(torch.randn_like(x1))
 
    def log_p1(self, x):
        """log p_1^base(x) on the zero-CoM subspace, x: (B, n, d) centred."""
        n, d = x.shape[-2:]
        k = (n - 1) * d                                    # subspace dimension
        return -0.5 * x.pow(2).sum((-2, -1)) / self.nu1 - 0.5 * k * math.log(2 * math.pi * self.nu1)
 
    def grad_log_p1(self, x):
        return -x / self.nu1


class GeometricNoiseSchedule(NoiseSchedule):
    """sigma(t) = s_min (s_max/s_min)^(1-t) sqrt(2 log(s_max/s_min))
    nu_t = s_max^2 (1 - (s_min/s_max)^(2t))
    Large noise early, small noise late. DW-4 in the paper: s_min = 1e-4, s_max = 3."""
 
    def __init__(self, sigma_min=1e-4, sigma_max=3.0):
        self.smin, self.smax = sigma_min, sigma_max
        self.r = sigma_max / sigma_min
 
    def sigma(self, t):
        t = torch.as_tensor(t)
        return self.smin * self.r ** (1 - t) * math.sqrt(2 * math.log(self.r))
 
    def nu(self, t):
        t = torch.as_tensor(t)
        return self.smax**2 * (1 - self.r ** (-2 * t))
 
 
class ConstantNoiseSchedule(NoiseSchedule):
    """sigma(t) = sigma, nu_t = sigma^2 t"""
 
    def __init__(self, sigma=1.0):
        self.s = sigma
 
    def sigma(self, t):
        return torch.full_like(torch.as_tensor(t, dtype=torch.float32), self.s)
 
    def nu(self, t):
        return self.s**2 * torch.as_tensor(t)


def time_grid(schedule, n_steps, kind="nu"):
    """Time points 0 = t_0 < ... < t_N = 1.
    "uniform": equal dt. Unstable for the geometric schedule: sigma(0)^2 ~ 185 for DW-4, so
               one step of 1/100 multiplies the drift by ~1.85.
    "nu":      equal steps in F(t) = nu_t / nu_1 + t: dense where the base process injects
               its variance (t < 0.15), roughly uniform later; sigma^2 dt <= ~0.1 at 200 steps."""
    if kind == "uniform":
        return torch.linspace(0, 1, n_steps + 1)
    fine = torch.linspace(0, 1, 100 * n_steps + 1, dtype=torch.float64)
    F = schedule.nu(fine) / schedule.nu1 + fine
    targets = torch.linspace(0, 2, n_steps + 1, dtype=torch.float64)
    idx = torch.searchsorted(F, targets).clamp(max=len(fine) - 1)
    ts = fine[idx]
    ts[0], ts[-1] = 0.0, 1.0
    return ts.float()
 
 
@torch.no_grad()
def euler_maruyama(model, n_samples, n_steps=200, return_traj=False, generator=None, grid="nu"):
    """X_0 = 0, X_{k+1} = X_k + sigma(t_k) u(X_k, t_k) dt_k + sigma(t_k) sqrt(dt_k) xi_k
    (xi projected to zero CoM) on the time grid `time_grid(schedule, n_steps, grid)`. Also accumulates the path quantities needed for the SOC objective and the
    path importance weights (eq. 74):
        control_cost = int 1/2 |u|^2 dt,   stoch_int = int u . dB
    Returns X_1 (B, n, d), dict(control_cost, stoch_int[, traj (n_steps+1, B, n, d)])."""
    sched = model.schedule
    p = next(model.parameters())
    x = torch.zeros(n_samples, model.n, model.d, dtype=p.dtype, device=p.device)
    ts = time_grid(sched, n_steps, grid).to(dtype=p.dtype, device=p.device)
    cost = torch.zeros(n_samples, dtype=torch.float64, device=p.device)
    stoch = torch.zeros_like(cost)
    traj = [x] if return_traj else None
    for t0, t1 in zip(ts[:-1], ts[1:]):
        dt = t1 - t0
        u = model(x, t0)
        dB = center(torch.randn(x.shape, generator=generator, dtype=x.dtype, device=x.device)) * dt.sqrt()
        x = x + sched.sigma(t0) * (u * dt + dB)
        cost += 0.5 * u.pow(2).sum((1, 2)).double() * dt.double()
        stoch += (u * dB).sum((1, 2)).double()
        if return_traj:
            traj.append(x)
    out = {"control_cost": cost, "stoch_int": stoch}
    if return_traj:
        out["traj"] = torch.stack(traj)
    return x, out
 
 
