# Terminal cost, replay buffer, RAM loss
# ---------------------------------------------------------------------------
def terminal_cost_and_grad(x1, energy_fn, schedule, tau=1.0, max_grad_norm=None):
    """g(X_1) = log p_1^base(X_1) + E(X_1)/tau and grad g (zero CoM), in float64.
    max_grad_norm: optional per-particle clipping of grad g (official code: Clipper)."""
    x = x1.detach().double()
    with torch.enable_grad():
        xr = x.requires_grad_(True)
        E = energy_fn(xr)
        (gE,) = torch.autograd.grad(E.sum(), xr)
    x = x.detach()
    g = schedule.log_p1(x) + E.detach() / tau
    grad = center(gE / tau + schedule.grad_log_p1(x))
    grad = torch.nan_to_num(grad, nan=0.0, posinf=0.0, neginf=0.0)
    if max_grad_norm is not None:
        norm = grad.norm(dim=-1, keepdim=True)
        grad = center(grad * torch.clamp(max_grad_norm / (norm + 1e-6), max=1.0))
    return E.detach(), g, grad
 
 
class ReplayBuffer:
    """FIFO buffer of (X_1, grad g(X_1), E(X_1)) with uniform sampling."""
 
    def __init__(self, max_size, n, d, device="cpu"):
        self.max_size = max_size
        self.device = torch.device(device)
        self.x = torch.empty(max_size, n, d, dtype=torch.float32, device=self.device)
        self.grad = torch.empty(max_size, n, d, dtype=torch.float32, device=self.device)
        self.E = torch.empty(max_size, dtype=torch.float64, device=self.device)
        self.size, self.ptr = 0, 0
 
    def add(self, x, grad, E):
        for i in range(0, len(x), self.max_size):
            xb, gb, eb = x[i:i + self.max_size], grad[i:i + self.max_size], E[i:i + self.max_size]
            idx = (self.ptr + torch.arange(len(xb), device=self.device)) % self.max_size
            self.x[idx] = xb.to(self.device, torch.float32)
            self.grad[idx] = gb.to(self.device, torch.float32)
            self.E[idx] = eb.to(self.device, torch.float64)
            self.ptr = int((self.ptr + len(xb)) % self.max_size)
            self.size = min(self.size + len(xb), self.max_size)
 
    def sample(self, batch_size, generator=None):
        idx = torch.randint(0, self.size, (batch_size,), generator=generator, device=self.device)
        return self.x[idx], self.grad[idx]
 
 
def ram_loss(model, x1, grad_g, t_eps=1e-3):
    """Reciprocal Adjoint Matching loss (13) for a batch from the buffer:
        t ~ U[t_eps, 1], X_t ~ p^base_{t|1}(. | X_1),
        L = lambda(t)/2 || u(X_t, t) + sigma(t) grad g ||^2  =  1/2 || s(X_t, t) + grad g ||^2
    (sum over particles and coordinates, mean over the batch)."""
    t = t_eps + (1 - t_eps) * torch.rand(x1.shape[0], dtype=x1.dtype, device=x1.device)
    xt = model.schedule.sample_posterior(t, x1)
    s = model.score(xt, t)
    return 0.5 * (s + grad_g).pow(2).sum((1, 2)).mean()
 
 
