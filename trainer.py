# Training loop: Algorithm 1
# ---------------------------------------------------------------------------
def train(model, energy_fn, *, n_outer=1000, n_new=512, buffer_size=10000, n_inner=500,
          batch_size=512, lr=3e-4, n_em_steps=200, tau=1.0, max_grad_norm=None,
          grad_clip=None, eval_every=50, eval_samples=2000, ref_energies=None, seed=0,
          drop_beyond=10.0, log=print):
    """Algorithm 1 (Adjoint Sampling).
    outer loop: n_new samples X_1 from the current model (Euler-Maruyama, no gradients),
                one energy-gradient evaluation each, pushed into the replay buffer
    inner loop: n_inner optimiser steps on the RAM loss with batches from the buffer
    Defaults are the paper's DW-4 settings (App. E.3).
    drop_beyond: samples with a non-finite energy or a coordinate beyond drop_beyond * sqrt(nu_1)
                 (10 * 3 = 30 for DW-4; reference samples stay within ~6) are not added to the
                 buffer. Early in training an occasional Euler-Maruyama path explodes (|x| ~ 1e8);
                 the MLP extrapolates linearly, so one such sample in the buffer wrecks training."""
    torch.manual_seed(seed)
    p = next(model.parameters())
    opt = torch.optim.Adam(model.parameters(), lr=lr)
    buf = ReplayBuffer(buffer_size, model.n, model.d, device=p.device)
    hist = {"outer": [], "loss": [], "E_new": [], "energy_evals": [], "dropped": [], "eval": []}
    limit = None if drop_beyond is None else drop_beyond * math.sqrt(model.schedule.nu1)
    t0 = time.perf_counter()
    for it in range(1, n_outer + 1):
        model.eval()
        x1, _ = euler_maruyama(model, n_new, n_em_steps)                       # line 5
        E, _, grad = terminal_cost_and_grad(x1, energy_fn, model.schedule, tau, max_grad_norm)  # line 7
        ok = torch.isfinite(E)
        if limit is not None:
            ok &= x1.flatten(1).abs().amax(1) <= limit
        buf.add(x1[ok], grad[ok], E[ok])                                       # line 8
        model.train()
        losses = []
        for _ in range(n_inner if buf.size else 0):                            # lines 9-13
            xb, gb = buf.sample(batch_size)
            xb, gb = xb.to(p), gb.to(p)                      # model dtype / device
            loss = ram_loss(model, xb, gb)
            opt.zero_grad(set_to_none=True)
            loss.backward()
            if grad_clip is not None:
                torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
            opt.step()
            losses.append(loss.detach())              # .item() here would sync the GPU every step
        hist["outer"].append(it)
        hist["loss"].append(float(torch.stack(losses).mean()) if losses else float("nan"))
        hist["E_new"].append(float(E[ok].median()) if ok.any() else float("nan"))
        hist["dropped"].append(int((~ok).sum()))
        if (~ok).sum() > n_new // 2:
            log(f"outer {it}: {int((~ok).sum())}/{n_new} samples exploded - the Euler-Maruyama grid is "
                "too coarse for the current drift; increase n_em_steps (>= 100, default 200)")
        hist["energy_evals"].append(it * n_new)
        if eval_every and (it % eval_every == 0 or it == n_outer):
            model.eval()
            ev, _ = evaluate(model, energy_fn, eval_samples, n_em_steps, tau, ref_energies)
            ev["outer"] = it
            hist["eval"].append(ev)
            log(f"outer {it:4d}  loss {hist['loss'][-1]:9.3f}  median E(new) {hist['E_new'][-1]:8.2f}  "
                f"dropped {sum(hist['dropped'][-eval_every:])}  "
                + "  ".join(f"{k} {v:.3f}" for k, v in ev.items() if k != "outer")
                + f"  ({time.perf_counter() - t0:.0f}s)")
    return hist

