# Evaluation
# ---------------------------------------------------------------------------
@torch.no_grad()
def evaluate(model, energy_fn, n_samples=2000, n_steps=200, tau=1.0, ref_energies=None):
    """SOC objective J (eq. 16, an upper bound on -log Z), normalised path-ESS (eq. 74-75),
    sample energies and, if given, W1 to reference energies."""
    x1, path = euler_maruyama(model, n_samples, n_steps)
    E, g, _ = terminal_cost_and_grad(x1, energy_fn, model.schedule, tau)
    J = path["control_cost"] + g
    logw = -(path["control_cost"] + path["stoch_int"] + g)
    logw = torch.nan_to_num(logw, nan=-math.inf)
    ess = float(torch.exp(2 * torch.logsumexp(logw, 0) - torch.logsumexp(2 * logw, 0)) / n_samples)
    out = {"J": float(J[torch.isfinite(J)].mean()), "path_ESS": ess,
           "E_mean": float(E.mean()), "E_median": float(E.median())}
    if ref_energies is not None:
        from scipy.stats import wasserstein_distance
        out["W1_E"] = float(wasserstein_distance(E.cpu().numpy(), np.asarray(ref_energies)))
    return out, x1
 
 
