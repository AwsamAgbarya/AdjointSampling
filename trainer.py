DEFAULTS = dict(
    system="dw4", ref="ref/lj13",                     # reference folder: W1 of energies during training
    sigma_min=1e-4, sigma_max=3.0,                   # geometric noise schedule (paper, App. E.3)
    hidden=256, n_layers=10, t_dim=32,                # MLP
    n_outer=1000, n_new=512, buffer_size=10000, n_inner=500, batch_size=512, lr=3e-4,
    n_em_steps=200, max_grad_norm=50.0, eval_every=50, eval_samples=2000, seed=0,
)


def default_device():
    return "cuda" if torch.cuda.is_available() else "cpu"


def build_model(cfg, device="cpu"):
    from dataset import SYSTEMS
    spec = SYSTEMS[cfg["system"]]
    schedule = GeometricNoiseSchedule(cfg["sigma_min"], cfg["sigma_max"])
    model = Model(spec["n"], spec["d"], schedule, hidden=cfg["hidden"], n_layers=cfg["n_layers"],
                  t_dim=cfg["t_dim"])
    return model.float().to(device)  # float32 even if the notebook sets float64 as default


def train_model(out, cfg, device=None):
    """Build the model for `cfg`, run Algorithm 1 on `device` (default: GPU if available) and
    save model.pt + history.json in `out`."""
    from dataset import SYSTEMS
    device = device or default_device()
    torch.manual_seed(cfg["seed"])
    model = build_model(cfg, device)
    ref_file = os.path.join(cfg["ref"], "energy.npy")
    ref_E = np.load(ref_file)[::20] if os.path.exists(ref_file) else None
    hist = train(model, SYSTEMS[cfg["system"]]["energy"], n_outer=cfg["n_outer"], n_new=cfg["n_new"],
                 buffer_size=cfg["buffer_size"], n_inner=cfg["n_inner"], batch_size=cfg["batch_size"],
                 lr=cfg["lr"], n_em_steps=cfg["n_em_steps"], max_grad_norm=cfg["max_grad_norm"],
                 eval_every=cfg["eval_every"], eval_samples=cfg["eval_samples"],
                 ref_energies=ref_E, seed=cfg["seed"])
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "history.json"), "w") as f:
        json.dump(hist, f)
    state = {k: v.cpu() for k, v in model.state_dict().items()}    # loadable without a GPU
    torch.save({"state_dict": state, "config": cfg},
               os.path.join(out, "model.pt"))            # written last: marks the run complete
    return model, hist


def load_model(out, device=None):
    """(model, history) from a folder written by train_model, on `device` (default: GPU if
    available). Works for checkpoints trained on GPU and loaded on a CPU-only machine."""
    ck = torch.load(os.path.join(out, "model.pt"), map_location="cpu", weights_only=False)
    model = build_model(ck["config"], device or default_device())
    model.load_state_dict(ck["state_dict"])
    model.eval()
    with open(os.path.join(out, "history.json")) as f:
        hist = json.load(f)
    return model, hist


def get_model(out, force=False, device=None, **overrides):
    """Load the trained model in `out` if it exists, otherwise train it (DEFAULTS + overrides)
    and save it. Prints the differences if the stored run used other settings.
    device: "cuda", "cpu", ... (default: GPU if available)."""
    cfg = {**DEFAULTS, **overrides}
    unknown = set(overrides) - set(DEFAULTS)
    if unknown:
        raise TypeError(f"unknown settings: {sorted(unknown)}")
    if os.path.exists(os.path.join(out, "model.pt")) and not force:
        model, hist = load_model(out, device)
        stored = torch.load(os.path.join(out, "model.pt"), map_location="cpu", weights_only=False)["config"]
        diff = {k: (stored.get(k), v) for k, v in cfg.items() if stored.get(k) != v}
        print(f"loaded {out}" + (f"; settings differ (stored, requested): {diff}, "
                                  "force=True retrains" if diff else ""))
        return model, hist
    device = device or default_device()
    print(f"training on {device} -> {out}")
    return train_model(out, cfg, device)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Train Adjoint Sampling (skipped if --out already "
                                             "holds a trained model, unless --force).")
    ap.add_argument("--out", default="runs/dw4_mlp")
    ap.add_argument("--force", action="store_true", help="retrain even if model.pt exists")
    ap.add_argument("--device", default="cuda", help="cuda / cpu / cuda:1 ... (default: GPU if available)")
    for k, v in DEFAULTS.items():
        ap.add_argument("--" + k.replace("_", "-"), type=type(v), default=v)
    a = vars(ap.parse_args(argv))
    out, force, device = a.pop("out"), a.pop("force"), a.pop("device")
    model, hist = get_model(out, force=force, device=device, **a)
    if hist["eval"]:
        print("final:", {k: round(v, 3) for k, v in hist["eval"][-1].items()})


if __name__ == "__main__":
    main()