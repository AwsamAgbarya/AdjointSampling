def _np(x):
    return x.detach().cpu().numpy() if torch.is_tensor(x) else np.asarray(x, dtype=float)
 
 
def positions(system, x):
    return _np(x).reshape(system.n, system.d).astype(float)
 
 
def energies(system, X, chunk=20000):
    """Energy of a batch of configurations (any shape that reshapes to (B, n, d)). +inf for NaN."""
    X = torch.as_tensor(_np(X), dtype=torch.float64).reshape(-1, system.n, system.d)
    with torch.no_grad():
        E = torch.cat([system.energy(X[i:i + chunk]).reshape(-1) for i in range(0, len(X), chunk)])
    return np.nan_to_num(E.cpu().numpy(), nan=np.inf)
 
 
def pair_distances(system, X):
    """All n(n-1)/2 pair distances of a batch, shape (B, n(n-1)/2)."""
    P = _np(X).reshape(-1, system.n, system.d)
    i, j = np.triu_indices(system.n, 1)
    return np.linalg.norm(P[:, i] - P[:, j], axis=-1)
 
 
def frame(system, x):
    """(center, B): B is an orthonormal d x d basis whose first two columns span the
    drawing plane (3D: the configuration's two main axes; third column = depth)."""
    p = positions(system, x)
    c = p.mean(0)
    if system.d == 2:
        return c, np.eye(2)
    _, _, Vt = np.linalg.svd(p - c)
    B = Vt.T
    if np.linalg.det(B) < 0:
        B[:, 2] *= -1
    return c, B @ _tilt(*VIEW_TILT_DEG)
 
 
VIEW_TILT_DEG = (20.0, 15.0)   # 3D view: rotation about plot axis 1, then axis 2 (degrees)
 
 
def _tilt(a_deg, b_deg):
    a, b = np.radians([a_deg, b_deg])
    Rx = np.array([[1, 0, 0], [0, np.cos(a), -np.sin(a)], [0, np.sin(a), np.cos(a)]])
    Ry = np.array([[np.cos(b), 0, np.sin(b)], [0, 1, 0], [-np.sin(b), 0, np.cos(b)]])
    return Rx @ Ry
 
 
def _config_lim(system, uv):
    return 1.12 * np.abs(uv).max() + 0.35 * min(system.wells or (1.0,))
 
 
def project(p, fr):
    c, B = fr
    return (np.atleast_2d(p) - c) @ B
 
 
def particle_direction(system, k, vec):
    """Direction in R^(n*d) that moves only particle k along `vec` (unit length)."""
    v = np.asarray(vec, float)
    out = np.zeros((system.n, system.d))
    out[k] = v / np.linalg.norm(v)
    return out
 
 
def _fmt_vec(v):
    return "(" + ", ".join(f"{a:.2f}" for a in v) + ")"
 
 
def relax(system, X, max_iter=1000):
    """Nearest local minimum of each configuration (L-BFGS on the energy)."""
    y = torch.as_tensor(_np(X), dtype=torch.float64).reshape(-1, system.n, system.d).clone()
    y.requires_grad_(True)
    opt = torch.optim.LBFGS([y], max_iter=max_iter, line_search_fn="strong_wolfe",
                            tolerance_grad=1e-9, tolerance_change=1e-14)
 
    def closure():
        opt.zero_grad()
        e = system.energy(y).sum()
        e.backward()
        return e
 
    for _ in range(3):
        opt.step(closure)
    return y.detach()
 
 
def distinct_minima(system, X, decimals=2):
    """Relax X and keep one configuration per distinct minimum energy, lowest first.
    Returns (configs (M, n, d), energies (M,), counts (M,)): counts = basin sizes in X."""
    Y = relax(system, X)
    E = energies(system, Y)
    keys, idx, counts = np.unique(np.round(E, decimals), return_index=True, return_counts=True)
    return Y[idx], E[idx], counts
 
 
