def slice_1d(system, x0, k, vec, ts):
    """E(x0 + t * dir) for t in ts, where dir moves only particle k along unit(vec)."""
    x0 = positions(system, x0)
    dvec = particle_direction(system, k, vec)
    return energies(system, x0[None] + np.asarray(ts, float)[:, None, None] * dvec[None])
 
 
def plot_particle_slice_1d(system, x0, k, vec=None, t_range=(-4, 4), n=400, axes=None,
                           n_terms=3, ylim=None, t_post=None):
    """Move particle k along `vec` (others fixed).
    axes = (ax_total, ax_pairs): total energy on top; the `n_terms` pair terms v(r_kj)
    that change most along the path below (one axis per measure, shared t-axis).
    For LJ-13 the total also contains the oscillator term, which is not a pair term."""
    if axes is None:
        _, axes = plt.subplots(2, 1, sharex=True, figsize=(6.5, 5), layout="constrained",
                               gridspec_kw={"height_ratios": [1.6, 1]})
    ax, axp = axes
    vec = np.asarray(vec if vec is not None else np.eye(system.d)[0], float)
    vec = vec / np.linalg.norm(vec)
    ts = np.linspace(*t_range, n)
    E = slice_1d(system, x0, k, vec, ts)
    p = positions(system, x0)
 
    ax.plot(ts, E, color=INK, lw=2.2, zorder=3)
    finite = E[np.isfinite(E)]
    if ylim is None:
        lo = finite.min()
        hi = lo + system.e_span
        if t_post is not None:
            hi = max(hi, slice_1d(system, x0, k, vec, [t_post])[0] + 0.15 * system.e_span)
        ylim = (lo - 0.06 * (hi - lo), hi)
    ax.set(ylim=ylim, ylabel="total energy E")
 
    if axp is not None:
        others = [j for j in range(system.n) if j != k]
        r = np.linalg.norm(p[k][None, None] + ts[None, :, None] * vec - p[others][:, None], axis=-1)
        V = system.pair(r)                                        # (n-1, len(ts))
        cap = system.pair_ylim[1]
        spread = np.ptp(np.clip(V, None, cap), axis=1)
        for c, idx in enumerate(np.argsort(-spread)[:n_terms]):
            axp.plot(ts, V[idx], color=SERIES[c], ls=DASHES[c], lw=1.6,
                     label=rf"$v(r_{{{k},{others[idx]}}})$")
        axp.axhline(0, color=AXIS, lw=0.8, zorder=0)
        axp.set(ylim=system.pair_ylim, ylabel="pair term")
        axp.legend(loc="lower right", bbox_to_anchor=(1, 1), ncol=n_terms, fontsize=7.5,
                   borderaxespad=0.2, handlelength=2.2)
        title_note = f"{n_terms} pair terms that change most" if system.n > 4 else ""
        if title_note:
            axp.set_title(title_note, fontsize=8, color=INK2, loc="left")
 
    for a in (ax, axp):
        if a is None:
            continue
        a.axvline(0, color=MUTED, lw=0.8, ls="--", zorder=0)
        if t_post is not None:
            a.axvline(t_post, color=MOVE_COLOR, lw=1.0, ls="--", zorder=0)
    ax.annotate("before", (0, 1), xycoords=("data", "axes fraction"), xytext=(0, 2),
                textcoords="offset points", ha="center", va="bottom", fontsize=8, color=INK2)
    if t_post is not None:
        e_post = slice_1d(system, x0, k, vec, [t_post])[0]
        ax.scatter([t_post], [e_post], s=45, color=MOVE_COLOR, edgecolor=SURFACE, lw=1.5, zorder=4)
        ax.annotate("after", (t_post, 1), xycoords=("data", "axes fraction"), xytext=(0, 2),
                    textcoords="offset points", ha="center", va="bottom", fontsize=8, color=MOVE_COLOR)
    (axp or ax).set_xlabel(f"displacement t of particle {k} along {_fmt_vec(vec)}")
    ax.set_xlim(t_range)
    return axes
 
 
def _auto_t_post(system, x0, k, vec, t_range, n, min_shift):
    """Deepest local minimum of the slice at least `min_shift` away from the start."""
    ts = np.linspace(*t_range, n)
    E = slice_1d(system, x0, k, vec, ts)
    is_min = np.r_[False, (E[1:-1] < E[:-2]) & (E[1:-1] <= E[2:]), False]
    cand = np.where(is_min & (np.abs(ts) >= min_shift))[0]
    if len(cand):
        return ts[cand[np.argmin(E[cand])]]
    return ts[0] if E[0] < E[-1] else ts[-1]
 
 
def plot_move(system, x0, k, vec=None, t_range=(-4, 4), t_post=None, min_shift=None, n=400,
              lim=None, n_terms=3, figsize=(14, 4.8)):
    """Before configuration | 1D slice (+ pair terms) | after configuration.
    If t_post is None, the 'after' state is the deepest local minimum of the slice."""
    vec = np.asarray(vec if vec is not None else np.eye(system.d)[0], float)
    vec = vec / np.linalg.norm(vec)
    if min_shift is None:
        min_shift = 0.25 * max(system.wells or (1.0,))
    if t_post is None:
        t_post = _auto_t_post(system, x0, k, vec, t_range, n, min_shift)
 
    pre = positions(system, x0)
    post = pre.copy()
    post[k] += t_post * vec
    e_pre, e_post = slice_1d(system, pre, k, vec, [0.0, t_post])
    fr = frame(system, pre)
    if lim is None:
        lim = _config_lim(system, project(np.vstack([pre, post]), fr)[:, :2])
 
    fig = plt.figure(figsize=figsize, layout="constrained")
    gs = fig.add_gridspec(2, 3, width_ratios=[1, 1.6, 1], height_ratios=[1.6, 1])
    a_pre, a_post = fig.add_subplot(gs[:, 0]), fig.add_subplot(gs[:, 2])
    a_E = fig.add_subplot(gs[0, 1])
    a_V = fig.add_subplot(gs[1, 1], sharex=a_E)
    plot_configuration(system, pre, ax=a_pre, lim=lim, fr=fr, highlight=k,
                       title=f"before: E = {e_pre:.2f}")
    plot_particle_slice_1d(system, pre, k, vec=vec, t_range=t_range, n=n, axes=(a_E, a_V),
                           n_terms=n_terms, t_post=t_post)
    plt.setp(a_E.get_xticklabels(), visible=False)
    plot_configuration(system, post, ax=a_post, lim=lim, fr=fr, highlight=k, ghost=pre[k],
                       title=f"after (t = {t_post:.2f}): E = {e_post:.2f}")
    fig.suptitle(f"{system.name}: moving particle {k}, others fixed", color=INK, fontsize=11)
    return fig, dict(before=a_pre, energy=a_E, pairs=a_V, after=a_post)
 
 
