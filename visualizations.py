def _bond_style(system, r):
    if system.barrier is not None:
        if abs(r - system.barrier) < 0.05:
            return dict(color=MUTED, ls=":", lw=1.4)
        if r < system.barrier:
            return dict(color=SERIES[0], ls="-", lw=1.6)
        return dict(color=SERIES[1], ls=(0, (3, 2)), lw=1.0)
    if system.bond_cutoff is None or r < system.bond_cutoff:
        return dict(color=SERIES[0], ls="-", lw=1.2)
    return None
 
 
def bond_legend_handles(system):
    if system.barrier is not None:
        return [Line2D([], [], color=SERIES[0], lw=1.6, label=f"r < {system.barrier:g} (short well)"),
                Line2D([], [], color=SERIES[1], lw=1.0, ls=(0, (3, 2)),
                       label=f"r > {system.barrier:g} (long well)"),
                Line2D([], [], color=MUTED, lw=1.4, ls=":", label="on the barrier")]
    if system.bond_cutoff is not None:
        return [Line2D([], [], color=SERIES[0], lw=1.2, label=f"r < {system.bond_cutoff:g}")]
    return []
 
 
def plot_configuration(system, x, ax=None, lim=None, fr=None, highlight=None, ghost=None,
                       title=None, labels=None, legend=False):
    """Particles with pair bonds.
    2D: drawn as is (centered).  3D: projected on the configuration's two main axes,
    far particles drawn smaller and lighter.
    fr:        drawing frame from `frame(system, x_ref)`; pass the same one to several
               panels (before/after) so they share coordinates.
    highlight: particle index to ring in MOVE_COLOR.
    ghost:     earlier position (d,) of the highlighted particle, drawn hollow with an arrow.
    labels:    particle indices (default: only for small systems; the highlight is always labeled)."""
    ax = ax or plt.gca()
    labels = system.n <= 6 if labels is None else labels
    p = positions(system, x)
    fr = fr or frame(system, p)
    q = project(p, fr)
    uv = q[:, :2]
    if system.d == 3:
        h = q[:, 2]
        depth = (h - h.min()) / max(np.ptp(h), 1e-9)            # 0 = far, 1 = near
    else:
        depth = np.ones(system.n)
    size = (70 if system.n > 6 else 110) * (0.55 + 0.45 * depth)
    far, near = np.array(to_rgb(MUTED)), np.array(to_rgb(INK))
    face = [tuple(far + (near - far) * t) for t in depth]
 
    for i, j in itertools.combinations(range(system.n), 2):
        style = _bond_style(system, np.linalg.norm(p[i] - p[j]))
        if style is not None:
            ax.plot(*uv[[i, j]].T, zorder=1, alpha=0.5 + 0.5 * min(depth[i], depth[j]), **style)
    if ghost is not None and highlight is not None:
        g = project(ghost, fr)[0, :2]
        ax.scatter(*g, s=size[highlight], facecolor="none", edgecolor=MUTED, lw=1.4, ls="--", zorder=2)
        ax.annotate("", xy=uv[highlight], xytext=g, zorder=2,
                    arrowprops=dict(arrowstyle="->", color=MOVE_COLOR, lw=1.4, shrinkA=7, shrinkB=7))
    for k in np.argsort(depth):                                   # far first
        ax.scatter(*uv[k], s=size[k], color=face[k], edgecolor=SURFACE, lw=1.5, zorder=3)
        if labels or k == highlight:
            ax.annotate(str(k), uv[k], ha="center", va="center", color="white",
                        fontsize=6 if system.n > 6 else 7, fontweight="bold", zorder=3)
    if highlight is not None:
        ax.scatter(*uv[highlight], s=size[highlight] * 2.4, facecolor="none",
                   edgecolor=MOVE_COLOR, lw=2, zorder=4)
    if lim is None:
        lim = _config_lim(system, uv)
    ax.set(xlim=(-lim, lim), ylim=(-lim, lim), aspect="equal", xticks=[], yticks=[])
    ax.grid(False)
    for s in ax.spines.values():
        s.set_visible(False)
    if title is not None:
        ax.set_title(title, fontsize=10)
    if legend:
        ax.legend(handles=bond_legend_handles(system), loc="lower center", fontsize=7,
                  bbox_to_anchor=(0.5, -0.12), ncol=3)
    return ax
 
 
