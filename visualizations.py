@dataclass
class System:
    name: str
    n: int                                # particles
    d: int                                # spatial dimension
    energy: Callable                      # torch (B, n, d) -> (B,)
    pair: Callable                        # numpy r -> contribution of ONE pair to E
    wells: tuple = ()                     # radii where the pair term is minimal
    barrier: Optional[float] = None       # DW: d0; bonds are classified short / long
    bond_cutoff: Optional[float] = None   # LJ: draw only pairs closer than this
    r_range: tuple = (0.0, 8.0)           # x-range of the pair-potential plot
    pair_ylim: tuple = (-6.0, 20.0)
    e_span: float = 40.0                  # energy range shown above the minimum in 1D slices
    contour_clip: float = 30.0            # same for contour plots
 
 
def dw4_system():
    from energy import DW_energy, DW_pair_potential, DW_A, DW_B, DW_C, DW_D0
    assert DW_A == 0, "well positions below assume a = 0"
    dr = np.sqrt(-DW_B / (2 * DW_C))
    return System("DW-4", 4, 2, DW_energy, DW_pair_potential,
                  wells=(DW_D0 - dr, DW_D0 + dr), barrier=DW_D0)
 
 
def lj13_system():
    from energy import LJ_energy, LJ_pair_potential, LJ_RM
    # LJ_energy sums every pair twice (iDEM convention), so one pair contributes 2 v(r).
    # LJ_pair_potential takes the squared distance.
    return System("LJ-13", 13, 3, LJ_energy, lambda r: 2.0 * LJ_pair_potential(np.asarray(r) ** 2),
                  wells=(LJ_RM,), bond_cutoff=1.3 * LJ_RM, r_range=(0.85, 3.0),
                  pair_ylim=(-2.5, 4.0), e_span=25.0, contour_clip=15.0)
 
 
