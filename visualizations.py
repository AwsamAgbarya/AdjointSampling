def slice_2d(system, x0, dir1, dir2, us, vs):
    """E(x0 + u * dir1 + v * dir2) on the grid us x vs; dir1, dir2 are full-space directions
    (shape (n, d) or flat). Returns an array of shape (len(vs), len(us))."""
    x0 = positions(system, x0)
    d1, d2 = (np.asarray(d, float).reshape(system.n, system.d) for d in (dir1, dir2))
    U, V = np.meshgrid(us, vs)
    X = x0[None] + U.ravel()[:, None, None] * d1[None] + V.ravel()[:, None, None] * d2[None]
    return energies(system, X).reshape(U.shape)
 
 
def _contour(ax, U, V, E, clip):
    E = np.nan_to_num(E, nan=np.inf)
    vmin = E[np.isfinite(E)].min()
    vmax = vmin + clip
    Ec = np.minimum(E, vmax)
    levels = np.linspace(vmin, vmax, 25)
    cs = ax.contourf(U, V, Ec, levels=levels, cmap=ENERGY_CMAP)
    ax.contour(U, V, Ec, levels=levels[:-1:3], colors="white", linewidths=0.4, alpha=0.6)
    cb = plt.colorbar(cs, ax=ax, shrink=0.85, pad=0.02)
    cb.set_label(f"energy (capped at min + {clip:g})", color=INK2, fontsize=8.5)
    cb.outline.set_visible(False)
    cb.locator = MaxNLocator(6)
    cb.update_ticks()
    cb.ax.tick_params(labelsize=8, colors=MUTED)
    ax.grid(False)
    return cs
 
 
def plot_particle_contour(system, x0, k, plane=None, extent=None, n=200, clip=None,
                          show_wells=True, ax=None, title=None, legend=True):
    """Move particle k over a plane while the others stay fixed; contour E.
    2D: the plane is the full space.  3D: a plane through particle k, by default parallel to
    the configuration's two main axes; or plane=(e1, e2) with two 3D vectors.
    Axes are plane coordinates relative to the configuration's center.
    Fixed particles fade with their distance from the plane (3D). Dashed circles: where
    the pair term with that particle is minimal (sphere of radius `wells` cut by the plane)."""
    ax = ax or plt.gca()
    clip = clip or system.contour_clip
    p = positions(system, x0)
    c, B = frame(system, p)
    if plane is not None:
        e1 = np.asarray(plane[0], float); e1 /= np.linalg.norm(e1)
        e2 = np.asarray(plane[1], float); e2 = e2 - (e2 @ e1) * e1; e2 /= np.linalg.norm(e2)
        B = np.column_stack([e1, e2] + ([np.cross(e1, e2)] if system.d == 3 else []))
    fr = (c, B)
    q = project(p, fr)
    uv = q[:, :2]
    dh = q[:, 2] - q[k, 2] if system.d == 3 else np.zeros(system.n)
 
    if extent is None:
        extent = np.abs(uv).max() + max(min(system.wells or (1.0,)), 1.0)
    us = np.linspace(-extent, extent, n)
    vs = np.linspace(-extent, extent, n)
    d1 = particle_direction(system, k, B[:, 0])
    d2 = particle_direction(system, k, B[:, 1])
    E = slice_2d(system, p, d1, d2, us - uv[k, 0], vs - uv[k, 1])
    U, V = np.meshgrid(us, vs)
    _contour(ax, U, V, E, clip)
 
    others = [j for j in range(system.n) if j != k]
    alpha = np.clip(1 - np.abs(dh) / 1.5, 0.25, 1.0) if system.d == 3 else np.ones(system.n)
    if show_wells:
        for j in others:
            for rad in system.wells:
                if rad > abs(dh[j]):
                    ax.add_patch(Circle(uv[j], np.sqrt(rad**2 - dh[j] ** 2), fill=False, ec="white",
                                        lw=0.8, ls=(0, (2, 2)), alpha=0.85 * alpha[j]))
    for j in others:
        ax.scatter(*uv[j], s=70 if system.n > 6 else 90, color=SERIES[1], edgecolor="white",
                   lw=1.2, alpha=alpha[j], zorder=4)
        if system.n <= 6:
            ax.annotate(str(j), uv[j], ha="center", va="center", fontsize=7, color="white",
                        fontweight="bold", zorder=5)
    ax.scatter(*uv[k], s=90, facecolor="none", edgecolor="white", lw=1.8, zorder=5, path_effects=_HALO)
    imin = np.unravel_index(np.nanargmin(np.where(np.isfinite(E), E, np.nan)), E.shape)
    ax.scatter([U[imin]], [V[imin]], marker="x", s=55, color="white", lw=1.8, zorder=5, path_effects=_HALO)
 
    plane_txt = "" if system.d == 2 else " (plane through it)"
    ax.set(xlim=(us[0], us[-1]), ylim=(vs[0], vs[-1]), aspect="equal",
           xlabel=f"position of particle {k}: axis 1" if system.d == 3 else f"x of particle {k}",
           ylabel=f"axis 2" if system.d == 3 else f"y of particle {k}")
    ax.set_title(title or f"{system.name}: E as particle {k} moves{plane_txt}", fontsize=10)
    if legend:
        handles = [
            Line2D([], [], ls="", marker="o", ms=8, mfc=SERIES[1], mec="white",
                   label="fixed particle" + (" (faded = off-plane)" if system.d == 3 else "")),
            # Line2D([], [], ls="", marker="o", ms=8, mfc="none", mec=INK, mew=1.8, label=f"start of particle {k}"),
            Line2D([], [], ls="", marker="x", ms=7, mec=INK, mew=1.8, label="lowest point in slice"),
        ]
        if show_wells:
            handles.append(Line2D([], [], color=MUTED, ls=(0, (2, 2)), lw=1,
                                  label="pair minimum r = " + " / ".join(f"{w:.2f}" for w in system.wells)))
        ax.legend(handles=handles, loc="upper left", bbox_to_anchor=(0, -0.13), ncol=1, fontsize=7.5)
    return ax
 
 
