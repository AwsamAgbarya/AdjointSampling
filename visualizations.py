def _acf(chains, max_lag):
    x = np.asarray(chains, float)
    x = x - x.mean(0)
    T = x.shape[0]
    n = 1 << (2 * T - 1).bit_length()
    f = np.fft.rfft(x, n=n, axis=0)
    acf = np.fft.irfft(f * np.conj(f), n=n, axis=0)[:T].mean(1)
    return acf[:max_lag] / acf[0]
 
 
def plot_mcmc_diagnostics(runs, n_trace=1, max_lag=200, window=None, figsize=(13, 3.8)):
    """runs: {label: dict with 'energies' (T, B) and optionally 'warm_energies' (W, B) and
    'energy_stride' (steps between rows, default 1)} (the result of run_mcmc or
    utils.load_run). Left: energy trace of the first run:
    warm-up shaded, mean over chains, 10-90% band across chains, n_trace single chains
    (window = (start, stop) zooms into a step range). Right: energy autocorrelation per run."""
    fig, (a_t, a_c) = plt.subplots(1, 2, figsize=figsize, layout="constrained",
                                   gridspec_kw={"width_ratios": [1.6, 1]})
    label0, r0 = next(iter(runs.items()))
    W = r0.get("warm_energies")
    E = np.asarray(r0["energies"])
    full = E if W is None else np.concatenate([np.asarray(W), E])
    s0 = r0.get("energy_stride", 1)
    t = np.arange(len(full)) * s0
    w = 0 if W is None else len(W)
    if w:
        a_t.axvspan(0, w, color=GRID, alpha=0.6, lw=0)
        a_t.annotate("warm-up", (w / 2, 1), xycoords=("data", "axes fraction"), xytext=(0, -4),
                     textcoords="offset points", ha="center", va="top", fontsize=8, color=INK2)
    q10, q90 = np.quantile(full, [0.1, 0.9], axis=1)
    a_t.fill_between(t, q10, q90, color=SERIES[0], alpha=0.18, lw=0, label="10-90% of chains")
    for j in range(n_trace):
        a_t.plot(t, full[:, j], color=SERIES[0], lw=0.5, alpha=0.6, label=f"chain {j}")
    a_t.plot(t, full.mean(1), color=INK, lw=1.4, label=f"mean of {full.shape[1]} chains")
    lo, hi = np.quantile(E, [0.001, 0.999])
    a_t.set(ylim=(lo - 0.1 * (hi - lo), hi + 0.15 * (hi - lo)), xlim=window or (0, t[-1]),
            xlabel="MCMC step", ylabel="energy E", title=f"energy trace: {label0}")
    a_t.legend(loc="upper right", ncol=4)
    for i, (label, r) in enumerate(runs.items()):
        s = r.get("energy_stride", 1)
        acf = _acf(r["energies"], max(2, max_lag // s + 1))
        a_c.plot(np.arange(len(acf)) * s, acf, color=SERIES[i % len(SERIES)], label=label)
    a_c.axhline(0, color=AXIS, lw=0.8)
    a_c.set(xlabel="lag (MCMC steps)", ylabel="autocorrelation of E", xlim=(0, max_lag),
            title="energy autocorrelation")
    a_c.legend(loc="upper right")
    return fig, {"trace": a_t, "acf": a_c}
 
 
