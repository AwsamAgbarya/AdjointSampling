def plot_training_history(hists, metrics=("loss", "W1_E", "J", "path_ESS"), figsize=None):
    """hists: {label: history dict from adjoint.train}. One panel per metric, x-axis =
    energy evaluations (n_new per outer iteration), one line per run (fixed colors)."""
    hists = hists if isinstance(hists, dict) else {"run": hists}
    titles = {"loss": "RAM loss (inner-loop mean)", "W1_E": "W1 of energy vs reference",
              "J": "SOC objective J (upper bound on -log Z)", "path_ESS": "path ESS (normalised)",
              "E_mean": "mean energy of samples"}
    fig, axes = plt.subplots(1, len(metrics), figsize=figsize or (4.2 * len(metrics), 3.4),
                             layout="constrained")
    for ax, m in zip(np.atleast_1d(axes), metrics):
        for i, (label, h) in enumerate(hists.items()):
            n_new = h["energy_evals"][0] if h["energy_evals"] else 1
            if m == "loss":
                x, y = np.asarray(h["energy_evals"]), np.asarray(h["loss"])
            else:
                ev = [e for e in h["eval"] if m in e]
                x = np.asarray([e["outer"] * n_new for e in ev])
                y = np.asarray([e[m] for e in ev])
            ax.plot(x, y, color=SERIES[i % len(SERIES)], lw=1.6 if m == "loss" else 2,
                    marker=None if m == "loss" else "o", ms=4, label=label)
        if m in ("loss", "W1_E"):
            ax.set_yscale("log")
        ax.set(title=titles.get(m, m), xlabel="energy evaluations")
    np.atleast_1d(axes)[0].legend(loc="upper right")
    return fig, axes