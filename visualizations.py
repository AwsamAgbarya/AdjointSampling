def plot_pair_potential(system, ax=None, ylim=None):
    ax = ax or plt.gca()
    r = np.linspace(*system.r_range, 800)
    ylim = ylim or system.pair_ylim
    ax.plot(r, system.pair(r), color=SERIES[0])
    marks = [(w, f"min r = {w:.2f}") for w in system.wells]
    if system.barrier is not None:
        marks.append((system.barrier, f"barrier r = {system.barrier:g}"))
    for rr, txt in marks:
        ax.axvline(rr, color=MUTED, lw=0.8, ls="--", zorder=0)
        ax.annotate(txt, (rr, ylim[1]), xytext=(3, -4), textcoords="offset points",
                    ha="left", va="top", fontsize=8, color=INK2)
    ax.axhline(0, color=AXIS, lw=0.8, zorder=0)
    ax.set(xlim=system.r_range, ylim=ylim, xlabel="pair distance r",
           ylabel="pair potential")
    return ax
 
 
def plot_pair_distance_hist(system, samples, ax=None, bins=80):
    """Density of pair distances. `samples`: one array of configurations, or a dict
    {label: configurations} to overlay several sets (reference vs. model, ...).
    Colors follow dict order, so a set keeps its color across figures."""
    ax = ax or plt.gca()
    if not isinstance(samples, dict):
        samples = {"samples": samples}
    edges = np.linspace(*system.r_range, bins + 1)
    for i, (label, X) in enumerate(samples.items()):
        r = pair_distances(system, X).ravel()
        ax.hist(r, bins=edges, density=True, histtype="step", lw=1.8, color=SERIES[i % len(SERIES)],
                label=f"{label} (n={len(_np(X).reshape(-1, system.n * system.d))})")
    for w in tuple(system.wells) + ((system.barrier,) if system.barrier is not None else ()):
        ax.axvline(w, color=MUTED, lw=0.8, ls="--", zorder=0)
    ax.set(xlim=system.r_range, xlabel="pair distance r", ylabel="density")
    ax.legend(loc="upper right")
    return ax
 
 
def plot_pair_overview(system, samples=None, figsize=(6.5, 5.2)):
    """Pair potential on top, pair-distance histogram(s) below, shared r-axis."""
    if samples is None:
        fig, ax = plt.subplots(figsize=(figsize[0], figsize[1] * 0.6), layout="constrained")
        return fig, plot_pair_potential(system, ax)
    fig, (a, b) = plt.subplots(2, 1, figsize=figsize, sharex=True, layout="constrained",
                               gridspec_kw={"height_ratios": [1.4, 1]})
    plot_pair_potential(system, a)
    a.set_xlabel("")
    plot_pair_distance_hist(system, samples, b)
    return fig, (a, b)
 
 
