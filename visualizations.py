def _as_sets(sets):
    return sets if isinstance(sets, dict) else {"samples": sets}
 
 
def _hist_sets(ax, values, edges, counts=None):
    for i, (label, v) in enumerate(values.items()):
        c = SERIES[i % len(SERIES)]
        v = v[np.isfinite(v)]
        n = counts[label] if counts else len(v)
        if i == 0:
            ax.hist(v, bins=edges, density=True, color=c, alpha=0.18, lw=0)
        ax.hist(v, bins=edges, density=True, histtype="step", color=c, lw=1.8,
                label=f"{label} ({n:,} configs)")
 
 
def plot_energy_hist(system, sets, ax=None, bins=70, energies=None, q=(0.001, 0.999)):
    """Energy histograms. energies: optional {label: E} to skip recomputing."""
    ax = ax or plt.gca()
    sets = _as_sets(sets)
    E = {k: (np.asarray(energies[k]) if energies and k in energies else energies_of(system, X))
         for k, X in sets.items()}
    allE = np.concatenate([e[np.isfinite(e)] for e in E.values()])
    lo, hi = np.quantile(allE, q)
    _hist_sets(ax, E, np.linspace(lo, hi, bins + 1))
    ax.set(xlim=(lo, hi), xlabel="energy E", ylabel="density", title=f"{system.name}: energy")
    ax.legend(loc="upper right")
    return ax
 
 
def energies_of(system, X):
    return energies(system, X)
 
 
def plot_pair_distance_sets(system, sets, ax=None, bins=80):
    """Pair-distance histograms, same overlay convention as plot_energy_hist."""
    ax = ax or plt.gca()
    sets = _as_sets(sets)
    R = {k: pair_distances(system, X).ravel() for k, X in sets.items()}
    counts = {k: len(_np(X).reshape(-1, system.n * system.d)) for k, X in sets.items()}
    _hist_sets(ax, R, np.linspace(*system.r_range, bins + 1), counts)
    for w in tuple(system.wells) + ((system.barrier,) if system.barrier is not None else ()):
        ax.axvline(w, color=MUTED, lw=0.8, ls="--", zorder=0)
    ax.set(xlim=system.r_range, xlabel="pair distance r", ylabel="density",
           title=f"{system.name}: pair distances")
    ax.legend(loc="best")
    return ax
 
 
def plot_config_grid(system, X, nrows=2, ncols=6, axes=None, energies_=None, overlay=None, **kw):
    """Configurations in a grid, energy in each title.
    overlay(ax, i, x): optional callback drawn on top of panel i (e.g. a model sample)."""
    X = _np(X).reshape(-1, system.n, system.d)[: nrows * ncols]
    if axes is None:
        _, axes = plt.subplots(nrows, ncols, figsize=(1.9 * ncols, 2.0 * nrows), layout="constrained")
    axes = np.atleast_1d(axes).ravel()
    E = energies(system, X) if energies_ is None else np.asarray(energies_)
