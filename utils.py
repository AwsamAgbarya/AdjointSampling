def autocorr_time(chains, c=5.0):
    """Integrated autocorrelation time (in steps) of a scalar, chains: (T, B).
    Chain-averaged autocorrelation function + Sokal's automatic window (as in emcee)."""
    x = np.asarray(chains, float)
    T = x.shape[0]
    x = x - x.mean(0)
    n = 1 << (2 * T - 1).bit_length()
    f = np.fft.rfft(x, n=n, axis=0)
    acf = np.fft.irfft(f * np.conj(f), n=n, axis=0)[:T].mean(1)
    acf /= acf[0]
    taus = 2.0 * np.cumsum(acf) - 1.0
    window = np.arange(T) < c * taus
    m = np.argmin(window) if not window.all() else T - 1
    return float(taus[m])


def split_rhat(chains):
    """Split-R-hat (Gelman et al.) of a scalar, chains: (T, B). ~1.00 = chains agree."""
    x = np.asarray(chains, float)
    h = x.shape[0] // 2
    x = np.concatenate([x[:h], x[h:2 * h]], axis=1)
    n = x.shape[0]
    W = x.var(0, ddof=1).mean()
    Bv = n * x.mean(0).var(ddof=1)
    return float(np.sqrt(((n - 1) / n * W + Bv / n) / W))


def summarize(res):
    E = res["energies"]
    tau = autocorr_time(E)
    ess = E.size / tau
    return {
        "method": res["method"], "step_size": round(res["step_size"], 5),
        "n_leapfrog": res["params"].get("n_leapfrog"),
        "accept": round(float(res["accept_rate"].mean()), 3),
        "E_mean": round(float(E.mean()), 3), "E_std": round(float(E.std()), 3),
        "tau_E_steps": round(tau, 1), "ESS_E": int(ess),
        "rhat_E": round(split_rhat(E), 4),
        "stuck_chains": int((res["accept_rate"] < 0.01).sum()),
        "grad_evals_per_ESS": round(res["grad_evals"] / ess, 1) if res["grad_evals"] else None,
        "ESS_per_s": round(ess / res["seconds"], 1), "seconds": round(res["seconds"], 1),
    }

def save_reference(folder, res, n, d, energy_fn=None, burn_in=0, min_accept=0.01, extra_meta=None):
    """Write a reference set as plain .npy files (memory-mappable for lazy loading):
        x.npy      (N, n, d) float32   samples, chain-major order
        energy.npy (N,)      float64   E(x)
        chain.npy  (N,)      int32     chain id    (splits are made per chain)
        step.npy   (N,)      int32     MCMC step of the sample
        run.npz              energy traces of all chains (every step), warm-up, acceptance
        meta.json            sampler settings and diagnostics. Written last: its presence
                             means the folder is complete (see is_complete / load_run).
    burn_in:    number of *stored* samples to drop at the start of every chain.
    min_accept: chains with a lower acceptance rate are stuck and are left out."""
    os.makedirs(folder, exist_ok=True)
    keep = np.where(res["accept_rate"] >= min_accept)[0]
    S = res["samples"][burn_in:][:, keep]                # (T, B_kept, D)
    T, B, _ = S.shape
    x = np.ascontiguousarray(S.transpose(1, 0, 2)).reshape(B * T, n, d)
    chain = np.repeat(np.arange(B, dtype=np.int32), T)
    step = np.tile(((np.arange(T) + burn_in + 1) * res["thin"]).astype(np.int32), B)
    E = res["energies"][step[:T] - 1][:, keep].T.reshape(-1)  # energies at the stored steps
    chain = keep[chain].astype(np.int32)                      # original chain ids
    if energy_fn is not None:                              # sanity: stored x reproduces E
        with torch.no_grad():
            Ex = energy_fn(torch.as_tensor(x[:1000], dtype=torch.float64)).numpy()
        assert np.allclose(Ex, E[:1000], atol=1e-3 * (1 + np.abs(E[:1000]).max())), "energy mismatch"
    np.save(os.path.join(folder, "x.npy"), x.astype(np.float32))
    np.save(os.path.join(folder, "energy.npy"), E)
    np.save(os.path.join(folder, "chain.npy"), chain)
    np.save(os.path.join(folder, "step.npy"), step)
    np.savez(os.path.join(folder, "run.npz"), energies=res["energies"].astype(np.float32),
             warm_energies=res["warm_energies"].astype(np.float32), accept_rate=res["accept_rate"])
    meta = {"n": n, "d": d, "method": res["method"], "params": res["params"], "thin": res["thin"],
            "warmup": res["warmup"], "burn_in_stored": burn_in, "n_chains": B,
            "dropped_chains": [int(c) for c in np.setdiff1d(np.arange(len(res["accept_rate"])), keep)],
            "samples_per_chain": T, "step_size": res["step_size"], "seconds": res["seconds"],
            "grad_evals": res["grad_evals"], "energy_evals": res["energy_evals"],
            "summary": summarize(res), **(extra_meta or {})}
    tmp = os.path.join(folder, "meta.json.tmp")
    with open(tmp, "w") as f:
        json.dump(meta, f, indent=2, default=float)
    os.replace(tmp, os.path.join(folder, "meta.json"))      # atomic: no half-written marker
    return meta


def is_complete(folder):
    """True if `folder` holds a finished reference run (also folders saved before run.npz existed)."""
    return all(os.path.exists(os.path.join(folder, f)) for f in ("meta.json", "x.npy", "energy.npy"))


def load_run(folder, samples=False):
    """Rebuild a run from disk, usable like the result of run_mcmc for summaries and
    plot_mcmc_diagnostics:  energies (T, B), warm_energies, accept_rate, summary, meta, ...
    samples=True adds samples (T, B_kept, n*d) as a memory-mapped view of x.npy.
    Folders written before run.npz existed: the energy trace is rebuilt from the stored
    samples (every `thin` steps, energy_stride = thin) and there is no warm-up trace."""
    with open(os.path.join(folder, "meta.json")) as f:
        meta = json.load(f)
    B, T = meta["n_chains"], meta["samples_per_chain"]
    res = {"method": meta["method"], "params": meta["params"], "thin": meta["thin"],
           "warmup": meta["warmup"], "step_size": meta.get("step_size", meta["params"].get("step_size")),
           "seconds": meta.get("seconds"), "grad_evals": meta.get("grad_evals"),
           "energy_evals": meta.get("energy_evals"), "summary": meta["summary"], "meta": meta,
           "folder": folder}
    run_file = os.path.join(folder, "run.npz")
    if os.path.exists(run_file):
        run = np.load(run_file)
        res.update(energies=run["energies"], warm_energies=run["warm_energies"],
                   accept_rate=run["accept_rate"], energy_stride=1)
    else:
        E = np.load(os.path.join(folder, "energy.npy"))
        res.update(energies=E.reshape(B, T).T, warm_energies=None, accept_rate=None,
                   energy_stride=meta["thin"])
    if samples:
        x = np.load(os.path.join(folder, "x.npy"), mmap_mode="r")
        res["samples"] = x.reshape(B, T, -1).transpose(1, 0, 2)
    return res