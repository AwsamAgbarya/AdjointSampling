def center(x):
    "Translation invariance: zero centre of mass, x: (B, n, d). Shared by dataset, models, trainer."
    return x - x.mean(dim=1, keepdim=True)


def prerelax(target, x, n_steps=300, lr=0.01, max_disp=0.05):
    "Capped gradient descent at most max_disp to remove far-out starts whose gradients are too large for the step size"
    x = torch.as_tensor(x, dtype=torch.float64).clone()
    for _ in range(n_steps):
        _, g = target.U_and_grad(x)
        g = torch.nan_to_num(g, nan=0.0, posinf=0.0, neginf=0.0)
        scale = torch.clamp(max_disp / (lr * g.norm(dim=-1, keepdim=True) + 1e-12), max=1.0)
        x = x - lr * scale * g
    return x


def init_gaussian(B, n, d, scale=2.5, seed=0):
    "Isotropic Gaussian positions, centred. Fine for DW-4 (soft core)."
    g = torch.Generator().manual_seed(seed)
    x = scale * torch.randn(B, n, d, generator=g, dtype=torch.float64)
    return (x - x.mean(1, keepdim=True)).reshape(B, n * d)


def init_cluster(B, n, d, radius=1.6, min_dist=0.9, seed=0, max_tries=10000):
    "particles placed one by one, uniformly in a ball of `radius`, rejecting candidates closer than `min_dist` to any placed particle."
    g = torch.Generator().manual_seed(seed)
    x = torch.zeros(B, n, d, dtype=torch.float64)
    for k in range(n):
        todo = torch.ones(B, dtype=torch.bool)
        for _ in range(max_tries):
            m = int(todo.sum())
            v = torch.randn(m, d, generator=g, dtype=torch.float64)
            r = radius * torch.rand(m, 1, generator=g, dtype=torch.float64) ** (1 / d)
            cand = v / v.norm(dim=-1, keepdim=True) * r
            if k == 0:
                ok = torch.ones(m, dtype=torch.bool)
            else:
                ok = (x[todo, :k] - cand[:, None]).norm(dim=-1).min(-1).values >= min_dist
            idx = todo.nonzero().squeeze(1)[ok]
            x[idx, k] = cand[ok]
            todo[idx] = False
            if not todo.any():
                break
        else:
            raise RuntimeError("init_cluster: increase radius or decrease min_dist")
    return (x - x.mean(1, keepdim=True)).reshape(B, n * d)


def run_mcmc(target, sampler, x0, warmup=2000, steps=20000, thin=10, adapt=True, adapt_frac=0.75, adapt_rate=0.05, log_every=1000, seed=0, store_dtype=np.float32):
    """B parallel chains. Warm-up: Robbins-Monro on log(step size) towards
    sampler.target_accept for the first adapt_frac of warm-up, then the step size is fixed
    to the average of the second half of the adaptation phase. The rest of warm-up is
    discarded burn-in at the final step size.

    Returns a dict with
      samples      (steps // thin, B, n*d)  every thin-th state
      energies     (steps, B)               E (not U) at every step, for diagnostics
      warm_energies(warmup, B)              E during warm-up, for burn-in plots
      accept_rate  (B,), step_size, n_leapfrog, grad_evals, seconds, ...
    """
    torch.manual_seed(seed)
    x = torch.as_tensor(x0, dtype=torch.float64).reshape(x0.shape[0], -1).clone()
    B, D = x.shape
    state = sampler.init_state(target, x)
    temp = 1.0 / target.beta

    n_adapt = int(adapt_frac * warmup) if adapt else 0
    log_eps, hist = math.log(sampler.step_size), []
    warm_E = np.empty((warmup, B))
    t0 = time.perf_counter()
    for t in range(warmup):
        state, acc_prob, _ = sampler.step(target, state)
        warm_E[t] = (state["U"] * temp).cpu().numpy()
        if t < n_adapt:
            log_eps += adapt_rate * (acc_prob.mean().item() - sampler.target_accept)
            sampler.step_size = math.exp(log_eps)
            if t >= n_adapt // 2:
                hist.append(log_eps)
            if t == n_adapt - 1:
                sampler.step_size = math.exp(float(np.mean(hist)))
    if log_every:
        print(f"  {type(sampler).__name__} warm-up done: step size {sampler.step_size:.4g}"
              f"{', L = %d' % sampler.n_leapfrog if hasattr(sampler, 'n_leapfrog') else ''}, "
              f"{time.perf_counter() - t0:.0f}s", flush=True)

    samples = np.empty((steps // thin, B, D), dtype=store_dtype)
    energies = np.empty((steps, B))
    n_acc = torch.zeros(B, dtype=torch.float64)
    t1 = time.perf_counter()
    for t in range(1, steps + 1):
        state, _, accepted = sampler.step(target, state)
        n_acc += accepted
        energies[t - 1] = (state["U"] * temp).cpu().numpy()
        if t % thin == 0:
            samples[t // thin - 1] = state["x"].cpu().numpy()
        if log_every and t % log_every == 0:
            print(f"  {type(sampler).__name__}: step {t}/{steps}, accept {n_acc.mean().item() / t:.3f}, "
                  f"{time.perf_counter() - t1:.0f}s", flush=True)
    L = getattr(sampler, "n_leapfrog", 0)               # MH: no gradient evaluations
    return {
        "method": type(sampler).__name__,
        "params": sampler.describe(),
        "samples": samples,
        "energies": energies,
        "warm_energies": warm_E,
        "accept_rate": (n_acc / steps).cpu().numpy(),
        "step_size": sampler.step_size,
        "thin": thin,
        "warmup": warmup,
        "grad_evals": (warmup + steps) * B * L,
        "energy_evals": (warmup + steps) * B * max(L, 1),
        "seconds": time.perf_counter() - t0,
        "x_final": state["x"].detach().cpu().numpy(),
    }


